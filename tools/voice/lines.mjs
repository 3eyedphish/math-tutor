// Lists every sentence the Little learner can say, for tools/voice/make.py to record.
// Usage: node tools/voice/lines.mjs          -> writes tools/voice/lines.json
//        node tools/voice/lines.mjs --ids    -> writes src/spell/clip-ids.js from public/voice/*.mp3
import { writeFileSync, readdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { allLessons, makeRound, roundLines, fixedLines } from "../../src/little/engine.js";
import { clipId, sentences } from "../../src/spell/voice-clips.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
export function allSentences() {
  const set = new Set();
  const add = (line) => { for (const s of sentences(line)) set.add(s); };
  fixedLines().forEach(add);
  // Questions are random: make many rounds of every lesson until no new sentence turns up.
  let seed = 7; const rnd = () => (seed = (seed * 16807) % 2147483647) / 2147483647;
  for (const subj of ["math", "abc"]) for (const l of allLessons(subj)) {
    let quiet = 0;
    while (quiet < 300) { const n = set.size; roundLines(makeRound(l, { name: "Sam" }, rnd)).forEach(add); quiet = set.size === n ? quiet + 1 : 0; }
  }
  // The child's own name is different in every family: its letters are recorded one by one instead.
  for (const s of [...set]) if (/Sam/.test(s)) set.delete(s);
  return [...set].sort();
}

if (process.argv.includes("--ids")) {
  const dir = join(root, "public/voice");
  const ids = existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith(".mp3")).map((f) => f.slice(0, -4)).sort() : [];
  writeFileSync(join(root, "src/spell/clip-ids.js"), `// Generated by tools/voice/lines.mjs --ids: the recordings in public/voice. Do not edit.\nexport const CLIP_IDS = "${ids.join(" ")}";\n`);
  console.log(`${ids.length} clip ids`);
} else if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const lines = allSentences().map((text) => ({ id: clipId(text), text }));
  const ids = new Set(lines.map((l) => l.id));
  if (ids.size !== lines.length) throw new Error("clip id collision");
  writeFileSync(join(root, "tools/voice/lines.json"), JSON.stringify(lines, null, 0).replace(/},{/g, "},\n{"));
  console.log(`${lines.length} sentences`);
}
